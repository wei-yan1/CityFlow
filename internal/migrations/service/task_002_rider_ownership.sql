-- Rider performance profiles are Task-owned. The legacy view must be removed
-- before this table can exist; the local bootstrap script performs that one-time
-- compatibility cleanup. No foreign key crosses into Identity.
CREATE TABLE IF NOT EXISTS rider_profiles (
    id                    CHAR(36) NOT NULL,
    user_id               CHAR(36) NOT NULL,
    display_name          VARCHAR(80) NOT NULL,
    vehicle_type          VARCHAR(24) NOT NULL,
    status                VARCHAR(20) NOT NULL DEFAULT 'OFFLINE',
    service_types         JSON NOT NULL,
    service_area          VARCHAR(160) NULL,
    max_distance_meters   INT UNSIGNED NOT NULL DEFAULT 5000,
    max_concurrent_tasks  SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    rating                DECIMAL(3,2) NOT NULL DEFAULT 5.00,
    completed_tasks       INT UNSIGNED NOT NULL DEFAULT 0,
    on_time_rate          DECIMAL(5,2) NOT NULL DEFAULT 100.00,
    current_latitude      DECIMAL(10,7) NULL,
    current_longitude     DECIMAL(10,7) NULL,
    location_updated_at   DATETIME(3) NULL,
    created_at            DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at            DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY rider_profiles_user_unique (user_id),
    KEY rider_profiles_dispatch_idx (status, vehicle_type),
    KEY rider_profiles_location_idx (current_latitude, current_longitude),
    CONSTRAINT rider_vehicle_check CHECK (vehicle_type IN ('WALK', 'BICYCLE', 'E_BIKE', 'CAR', 'OTHER')),
    CONSTRAINT rider_status_check CHECK (status IN ('OFFLINE', 'AVAILABLE', 'BUSY', 'SUSPENDED')),
    CONSTRAINT rider_rating_check CHECK (rating BETWEEN 0 AND 5),
    CONSTRAINT rider_on_time_rate_check CHECK (on_time_rate BETWEEN 0 AND 100),
    CONSTRAINT rider_latitude_check CHECK (current_latitude IS NULL OR current_latitude BETWEEN -90 AND 90),
    CONSTRAINT rider_longitude_check CHECK (current_longitude IS NULL OR current_longitude BETWEEN -180 AND 180)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS rider_feedback (
    id CHAR(36) NOT NULL PRIMARY KEY,
    rider_id CHAR(36) NOT NULL,
    task_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    rating TINYINT NULL,
    amount_fen BIGINT NULL,
    comment VARCHAR(600) NULL,
    reason VARCHAR(200) NULL,
    details TEXT NULL,
    images JSON NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'RECORDED',
    resolution_note VARCHAR(500) NULL,
    resolved_by CHAR(36) NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    resolved_at DATETIME(3) NULL,
    KEY rider_feedback_rider (rider_id, kind, created_at),
    KEY rider_feedback_task (task_id, user_id, kind, created_at),
    KEY rider_feedback_reports (kind, status, created_at),
    CONSTRAINT rider_feedback_rider_fk FOREIGN KEY(rider_id) REFERENCES rider_profiles(id),
    CONSTRAINT rider_feedback_task_fk FOREIGN KEY(task_id) REFERENCES tasks(id),
    CONSTRAINT rider_feedback_kind_check CHECK(kind IN ('REVIEW','TIP','REPORT','CALL')),
    CONSTRAINT rider_feedback_status_check CHECK(status IN ('PUBLISHED','RECORDED','OPEN','RESOLVED','DISMISSED')),
    CONSTRAINT rider_feedback_rating_check CHECK(rating IS NULL OR (rating >= 1 AND rating <= 5)),
    CONSTRAINT rider_feedback_amount_check CHECK(amount_fen IS NULL OR amount_fen > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
