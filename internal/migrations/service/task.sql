-- Task-owned tables. tasks.created_by / tasks.worker_id and actor/reporter IDs
-- intentionally have no foreign keys to cityflow_identity.users: those are
-- references to another service, validated at the application/RPC boundary.
CREATE TABLE IF NOT EXISTS tasks (
    id                   CHAR(36) NOT NULL,
    title                VARCHAR(160) NOT NULL,
    description          TEXT NULL,
    task_type            VARCHAR(40) NOT NULL,
    priority             TINYINT UNSIGNED NOT NULL DEFAULT 0,
    pickup               TEXT NOT NULL,
    destination          TEXT NOT NULL,
    status               VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    created_by           CHAR(36) NOT NULL,
    worker_id            CHAR(36) NULL,
    created_at           DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at           DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    pickup_location      JSON NULL,
    destination_location JSON NULL,
    pickup_stops         JSON NULL,
    delivery_at          DATETIME(3) NULL,
    idempotency_key      VARCHAR(128) NULL,
    idempotency_hash     CHAR(64) NULL,
    destination_poi_id   VARCHAR(128) NULL,
    quoted_amount_fen    BIGINT NULL,
    contact_name         VARCHAR(80) NOT NULL DEFAULT '',
    contact_phone        VARCHAR(32) NOT NULL DEFAULT '',
    handover_note        TEXT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY task_user_idempotency (created_by, idempotency_key),
    KEY tasks_creator_status_created_idx (created_by, status, created_at, id),
    KEY tasks_worker_status_idx (worker_id, status, updated_at),
    KEY tasks_status_created_idx (status, created_at, id),
    KEY tasks_created_by_created_id_idx (created_by, created_at, id),
    CONSTRAINT tasks_priority_check CHECK (priority BETWEEN 0 AND 10),
    CONSTRAINT tasks_quote_amount_check CHECK (quoted_amount_fen IS NULL OR (quoted_amount_fen > 0 AND quoted_amount_fen <= 9007199254740991)),
    CONSTRAINT tasks_status_check CHECK (status IN ('OPEN', 'CLAIMED', 'ARRIVED', 'PROCESSING', 'COMPLETED', 'CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS task_events (
    id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    task_id     CHAR(36) NOT NULL,
    from_status VARCHAR(24) NULL,
    to_status   VARCHAR(24) NOT NULL,
    actor_id    CHAR(36) NULL,
    created_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY task_events_task_id_idx (task_id, created_at),
    KEY task_events_actor_idx (actor_id),
    CONSTRAINT task_events_task_fk FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS task_incidents (
    id            CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    task_id       CHAR(36) NOT NULL,
    reporter_id   CHAR(36) NOT NULL,
    reporter_role VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    kind          VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    note          VARCHAR(500) NOT NULL DEFAULT '',
    image_urls    JSON NOT NULL,
    status        VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'OPEN',
    resolution    VARCHAR(500) NOT NULL DEFAULT '',
    resolved_by   CHAR(36) NULL,
    resolved_at   DATETIME(3) NULL,
    created_at    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY task_incidents_task (task_id, created_at, id),
    KEY task_incidents_reporter_idx (reporter_id),
    KEY task_incidents_status_created_idx (status, created_at, id),
    CONSTRAINT task_incidents_task_fk FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Rider performance profiles are owned by Task. user_id references the Identity
-- service and is validated at the RPC boundary, so it has no local foreign key.
CREATE TABLE IF NOT EXISTS rider_profiles (
    id                    CHAR(36) NOT NULL,
    user_id               CHAR(36) NOT NULL,
    display_name          VARCHAR(80) NOT NULL,
    vehicle_type          VARCHAR(24) NOT NULL,
    status                VARCHAR(20) NOT NULL DEFAULT 'OFFLINE',
    service_types         JSON NOT NULL,
    service_area          VARCHAR(160) NULL,
    max_distance_meters   INT UNSIGNED NOT NULL DEFAULT 5000,
    max_concurrent_tasks  SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    rating                DECIMAL(3,2) NOT NULL DEFAULT 5.00,
    completed_tasks       INT UNSIGNED NOT NULL DEFAULT 0,
    on_time_rate          DECIMAL(5,2) NOT NULL DEFAULT 100.00,
    current_latitude      DECIMAL(10,7) NULL,
    current_longitude     DECIMAL(10,7) NULL,
    location_updated_at   DATETIME(3) NULL,
    created_at            DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at            DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY rider_profiles_user_unique (user_id),
    KEY rider_profiles_dispatch_idx (status, vehicle_type),
    KEY rider_profiles_location_idx (current_latitude, current_longitude),
    CONSTRAINT rider_vehicle_check CHECK (vehicle_type IN ('WALK', 'BICYCLE', 'E_BIKE', 'CAR', 'OTHER')),
    CONSTRAINT rider_status_check CHECK (status IN ('OFFLINE', 'AVAILABLE', 'BUSY', 'SUSPENDED')),
    CONSTRAINT rider_rating_check CHECK (rating BETWEEN 0 AND 5),
    CONSTRAINT rider_on_time_rate_check CHECK (on_time_rate BETWEEN 0 AND 100),
    CONSTRAINT rider_latitude_check CHECK (current_latitude IS NULL OR current_latitude BETWEEN -90 AND 90),
    CONSTRAINT rider_longitude_check CHECK (current_longitude IS NULL OR current_longitude BETWEEN -180 AND 180)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS rider_feedback (
 id CHAR(36) NOT NULL PRIMARY KEY,
 rider_id CHAR(36) NOT NULL,
 task_id CHAR(36) NOT NULL,
 user_id CHAR(36) NOT NULL,
 kind VARCHAR(16) NOT NULL,
 rating TINYINT NULL,
 amount_fen BIGINT NULL,
 comment VARCHAR(600) NULL,
 reason VARCHAR(200) NULL,
 details TEXT NULL,
 images JSON NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'RECORDED',
 resolution_note VARCHAR(500) NULL,
 resolved_by CHAR(36) NULL,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 resolved_at DATETIME(3) NULL,
 KEY rider_feedback_rider (rider_id, kind, created_at),
 KEY rider_feedback_task (task_id, user_id, kind, created_at),
 KEY rider_feedback_reports (kind, status, created_at),
 CONSTRAINT rider_feedback_rider_fk FOREIGN KEY(rider_id) REFERENCES rider_profiles(id),
 CONSTRAINT rider_feedback_task_fk FOREIGN KEY(task_id) REFERENCES tasks(id),
 CONSTRAINT rider_feedback_kind_check CHECK(kind IN ('REVIEW','TIP','REPORT','CALL')),
 CONSTRAINT rider_feedback_status_check CHECK(status IN ('PUBLISHED','RECORDED','OPEN','RESOLVED','DISMISSED')),
 CONSTRAINT rider_feedback_rating_check CHECK(rating IS NULL OR (rating >= 1 AND rating <= 5)),
 CONSTRAINT rider_feedback_amount_check CHECK(amount_fen IS NULL OR amount_fen > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
